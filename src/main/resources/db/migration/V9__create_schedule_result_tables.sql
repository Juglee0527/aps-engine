CREATE TABLE schedule_run (
    schedule_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    execution_key UUID NOT NULL,
    planning_start TIMESTAMP WITH TIME ZONE NOT NULL,
    scheduling_end TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT pk_schedule_run PRIMARY KEY (schedule_run_id),
    CONSTRAINT uk_schedule_run_execution_key UNIQUE (execution_key),
    CONSTRAINT ck_schedule_run_period CHECK (
        scheduling_end >= planning_start
    ),
    CONSTRAINT ck_schedule_run_status CHECK (
        status IN ('COMPLETED')
    )
);

CREATE TABLE scheduled_operation (
    scheduled_operation_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    schedule_run_id BIGINT NOT NULL,
    production_order_id BIGINT NOT NULL,
    operation_id BIGINT NOT NULL,
    machine_id BIGINT NOT NULL,
    operation_sequence INTEGER NOT NULL,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    working_minutes BIGINT NOT NULL,
    delayed BOOLEAN NOT NULL,
    CONSTRAINT pk_scheduled_operation PRIMARY KEY (scheduled_operation_id),
    CONSTRAINT fk_scheduled_operation_run FOREIGN KEY (schedule_run_id)
        REFERENCES schedule_run (schedule_run_id) ON DELETE CASCADE,
    CONSTRAINT fk_scheduled_operation_order FOREIGN KEY (production_order_id)
        REFERENCES production_order (production_order_id),
    CONSTRAINT fk_scheduled_operation_operation FOREIGN KEY (operation_id)
        REFERENCES operation (operation_id),
    CONSTRAINT fk_scheduled_operation_machine FOREIGN KEY (machine_id)
        REFERENCES machine (machine_id),
    CONSTRAINT uk_scheduled_operation_run_order_operation UNIQUE (
        schedule_run_id,
        production_order_id,
        operation_id
    ),
    CONSTRAINT ck_scheduled_operation_sequence CHECK (
        operation_sequence >= 1
    ),
    CONSTRAINT ck_scheduled_operation_period CHECK (end_at > start_at),
    CONSTRAINT ck_scheduled_operation_working_minutes CHECK (
        working_minutes >= 1
    )
);

CREATE INDEX ix_scheduled_operation_run_start
    ON scheduled_operation (schedule_run_id, start_at);
CREATE INDEX ix_scheduled_operation_machine_start
    ON scheduled_operation (machine_id, start_at);
